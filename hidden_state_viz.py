def plot_interactive_layer_slider(hs: np.ndarray, meta: pd.DataFrame,
                                  model_key: str, out: Path) -> None:
    """
    Plotly scatter with a layer slider.  Each frame = one layer's PCA-2D
    coloured by signed projection onto the final-layer gender axis.
    Use the Play button to animate through all layers.
    """
    n_layers = hs.shape[1]
    final    = hs[:, -1, :]
    fm = (meta["protagonist_gender"] == "female").values
    mm = (meta["protagonist_gender"] == "male").values
    axis = final[fm].mean(0) - final[mm].mean(0)
    axis /= np.linalg.norm(axis) + 1e-9

    # Fixed PCA basis from the final layer so spatial layout is stable
    pca_basis = PCA(n_components=2, random_state=RANDOM_STATE).fit(final)

    frames, steps = [], []
    for l in range(n_layers):
        layer_vecs = hs[:, l, :]
        xy   = pca_basis.transform(layer_vecs)
        proj = layer_vecs @ axis
        vmin, vmax = float(np.percentile(proj, 5)), float(np.percentile(proj, 95))

        label = "Embedding" if l == 0 else f"Layer {l}"
        frames.append(go.Frame(
            data=[go.Scatter(
                x=xy[:, 0], y=xy[:, 1],
                mode="markers",
                marker=dict(
                    color=proj, colorscale="RdBu", reversescale=True,
                    size=5, opacity=0.6,
                    cmin=vmin, cmax=vmax,
                    colorbar=dict(title="Gender<br>projection"),
                    showscale=True,
                ),
                customdata=np.column_stack([
                    meta["protagonist_gender"].values,
                    meta["country"].values,
                    meta["person"].values,
                    proj.round(4).astype(str),
                ]),
                hovertemplate=(
                    "<b>%{customdata[0]}</b>  ·  %{customdata[2]}<br>"
                    "Country: %{customdata[1]}<br>"
                    "Gender projection: %{customdata[3]}"
                    "<extra></extra>"
                ),
            )],
            name=str(l),
            layout=go.Layout(title_text=(
                f"{model_key} : {label}  |  "
                "Blue = female-space  Red = male-space"
            )),
        ))
        steps.append(dict(
            args=[[str(l)], {"frame": {"duration": 0}, "mode": "immediate",
                             "transition": {"duration": 0}}],
            label=label, method="animate",
        ))

    # Initial frame (embedding layer)
    init_vecs = hs[:, 0, :]
    init_xy   = pca_basis.transform(init_vecs)
    init_proj = init_vecs @ axis

    fig = go.Figure(
        data=[go.Scatter(
            x=init_xy[:, 0], y=init_xy[:, 1],
            mode="markers",
            marker=dict(
                color=init_proj, colorscale="RdBu", reversescale=True,
                size=5, opacity=0.6,
                cmin=float(np.percentile(init_proj, 5)),
                cmax=float(np.percentile(init_proj, 95)),
                colorbar=dict(title="Gender<br>projection"),
            ),
            customdata=np.column_stack([
                meta["protagonist_gender"].values,
                meta["country"].values,
                meta["person"].values,
                init_proj.round(4).astype(str),
            ]),
            hovertemplate=(
                "<b>%{customdata[0]}</b>  ·  %{customdata[2]}<br>"
                "Country: %{customdata[1]}<br>"
                "Gender projection: %{customdata[3]}"
                "<extra></extra>"
            ),
        )],
        frames=frames,
    )
    fig.update_layout(
        title=dict(
            text=(
                f"{model_key} : Embedding Layer  |  "
                "Blue = female-space   Red = male-space<br>"
                "<span style='font-size:11px'>Use the slider or Play to walk "
                "through all transformer layers</span>"
            ),
            font=dict(size=13),
        ),
        xaxis_title="PC 1", yaxis_title="PC 2",
        width=1200, height=750,
        plot_bgcolor="#f8f8f8",
        hoverlabel=dict(bgcolor="white", font_size=12),
        sliders=[dict(
            active=0, steps=steps,
            x=0.05, y=0, len=0.9,
            currentvalue=dict(prefix="Layer: ", font=dict(size=13)),
            transition=dict(duration=0),
        )],
        updatemenus=[dict(
            type="buttons", showactive=False, y=0.05, x=0.0, xanchor="right",
            buttons=[
                dict(label="▶ Play", method="animate",
                     args=[None, {"frame": {"duration": 700}, "fromcurrent": True}]),
                dict(label="⏸ Pause", method="animate",
                     args=[[None], {"frame": {"duration": 0}, "mode": "immediate"}]),
            ],
        )],
    )
    path = out / "07_interactive_layer_slider.html"
    fig.write_html(str(path))
    print(f"    saved → {path.name}")


# Per-model driver 

def run_model(model_key: str, panel_layers: list[int] | None) -> None:
    hs_path   = HS_DIR / f"hidden_states_{model_key}.npy"
    meta_path = HS_DIR / f"extractor_meta_{model_key}.csv"

    if not hs_path.exists():
        print(f"  [skip] {model_key} : {hs_path.name} not found. "
              f"Run hidden_state_extractor_by_model.py first.")
        return

    print(f"  Model: {model_key}")

    hs   = np.load(hs_path)           # (n_stories, n_layers, hidden_dim)
    meta = pd.read_csv(meta_path)
    meta["region"] = meta["country"].map(REGION_MAP)

    # Drop stories where any layer/dim is NaN or Inf (float16 overflow artefacts)
    bad = ~np.isfinite(hs).all(axis=(1, 2))
    if bad.any():
        print(f"  Warning: dropping {bad.sum()} stories with NaN/Inf hidden states.")
        hs   = hs[~bad]
        meta = meta[~bad].reset_index(drop=True)

    n, L, H = hs.shape
    print(f"  Loaded: {n} stories  ×  {L} layers  ×  {H}-dim hidden states")

    if n == 0:
        print(f"  No valid stories — skipping {model_key}. "
              f"Re-extract with bfloat16 (see extractor dtype setting).")
        return

    out = OUT_DIR / model_key
    out.mkdir(parents=True, exist_ok=True)

    # Try to find the HF model ID for the description
    from hidden_state_extractor_by_model import HF_MODEL_MAP
    hf_id = HF_MODEL_MAP.get(model_key, "unknown")

    layers = _panel_layer_indices(L, panel_layers)
    print(f"  t-SNE panel layers: {layers}")

    describe_npy(hs, model_key, hf_id, out)
    plot_pca_final_layer(hs, meta, model_key, out)
    plot_tsne_layer_panels(hs, meta, model_key, layers, out)
    plot_gender_separation_curve(hs, meta, model_key, out)
    plot_probe_accuracy_curve(hs, meta, model_key, out)
    plot_region_separation_curve(hs, meta, model_key, out)
    plot_interactive_final_layer(hs, meta, model_key, out)
    plot_interactive_layer_slider(hs, meta, model_key, out)

    print(f"  All outputs : {out}/")


# Main 

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--model", default=None,
                   help="Single model key to visualise (default: all extracted).")
    p.add_argument("--panel-layers", nargs="+", type=int, default=None,
                   help="Layer indices for the t-SNE panel (default: auto).")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    if args.model:
        run_model(args.model, args.panel_layers)
    else:
        available = sorted(HS_DIR.glob("hidden_states_*.npy"))
        if not available:
            print(f"No .npy files found in {HS_DIR}. "
                  f"Run hidden_state_extractor_by_model.py first.")
            return
        for p in available:
            model_key = p.stem.replace("hidden_states_", "")
            run_model(model_key, args.panel_layers)


