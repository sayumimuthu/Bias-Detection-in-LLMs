def describe_npy(hs: np.ndarray, model_key: str,
                 hf_id: str, out: Path) -> None:
    """Write a plain-text description of the array to know what was loaded."""
    n, L, H = hs.shape
    lines = [
        f"File: hidden_states_{model_key}.npy",
        f"HF model: {hf_id}",
        f"",
        f"Array shape: ({n}, {L}, {H})",
        f"  axis 0 : {n} stories generated by {model_key}",
        f"  axis 1 : {L} layers",
        f"             layer  0  : token embedding output",
        f"             layers 1..{L-1}: transformer block outputs",
        f"  axis 2 : {H}-dimensional hidden state vector per story per layer",
        f"",
        f"Each vector [story_i, layer_j, :] is the mean of all token",
        f"hidden states in story_i at transformer depth layer_j.",
        f"",
        f"Memory: {hs.nbytes / 1e6:.1f} MB  (float32)",
    ]
    path = out / "00_what_is_npy.txt"
    path.write_text("\n".join(lines))
    for line in lines:
        print("   ", line)
    print()


def plot_pca_final_layer(hs: np.ndarray, meta: pd.DataFrame,
                         model_key: str, out: Path) -> None:
    """
    PCA-2D of the FINAL transformer layer, coloured four ways in a 2×2 grid.
    This is the single-panel equivalent of a t-SNE — fast and interpretable.
    """
    final = hs[:, -1, :]
    xy    = _pca2(final)

    person_cats = sorted(meta["person"].unique())
    person_pal  = dict(zip(person_cats, sns.color_palette("tab20", len(person_cats))))

    schemes = [
        ("protagonist_gender", GEN_COLORS,   "Protagonist Gender"),
        ("region",             REG_COLORS,   "Cultural Region"),
        ("model_family",       FAM_COLORS,   "Model Family"),
        ("person",             person_pal,   "Narrator Role"),
    ]

    fig, axes = plt.subplots(2, 2, figsize=(16, 13))
    fig.suptitle(
        f"Final-Layer Hidden States : PCA-2D\n{model_key}  "
        f"({hs.shape[0]} stories, layer {hs.shape[1]-1}, dim {hs.shape[2]})",
        fontsize=13, fontweight="bold",
    )
    for ax, (col, colors, title) in zip(axes.flat, schemes):
        for val, color in colors.items():
            mask = (meta[col] == val).values
            if not mask.any():
                continue
            ax.scatter(xy[mask, 0], xy[mask, 1],
                       c=color, alpha=0.40, s=8, linewidths=0, label=val)
        ax.set_title(title, fontweight="bold")
        ax.set_xlabel("PC 1"); ax.set_ylabel("PC 2")
        ax.legend(markerscale=3, fontsize=7, loc="best",
                  framealpha=0.7, edgecolor="none")
        ax.set_facecolor("#f8f8f8")

    plt.tight_layout()
    _save(fig, out / "01_pca_final_layer.png")


def plot_tsne_layer_panels(hs: np.ndarray, meta: pd.DataFrame,
                           model_key: str, panel_layers: list[int],
                           out: Path) -> None:
    """
    t-SNE at selected layers, coloured by protagonist gender.
    Shows how cluster structure evolves from embedding - final layer.
    """
    fig, axes = plt.subplots(1, len(panel_layers),
                             figsize=(len(panel_layers) * 4.2, 4.5))
    if len(panel_layers) == 1:
        axes = [axes]

    fig.suptitle(
        f"t-SNE at Selected Layers : {model_key}\n"
        "Does gender separation grow with depth?",
        fontsize=12, fontweight="bold",
    )
    for ax, layer_idx in zip(axes, panel_layers):
        print(f"    t-SNE layer {layer_idx} …")
        xy = _tsne2(hs[:, layer_idx, :])

        for gender, color in GEN_COLORS.items():
            mask = (meta["protagonist_gender"] == gender).values
            ax.scatter(xy[mask, 0], xy[mask, 1],
                       c=color, alpha=0.35, s=6, linewidths=0, label=gender)

        label = "Embedding" if layer_idx == 0 else f"Layer {layer_idx}"
        ax.set_title(label, fontweight="bold")
        ax.set_xticks([]); ax.set_yticks([])
        ax.set_facecolor("#f8f8f8")

    handles = [mpatches.Patch(color=c, label=g) for g, c in GEN_COLORS.items()]
    fig.legend(handles=handles, loc="lower right", fontsize=9,
               framealpha=0.85, ncol=2)
    plt.tight_layout()
    _save(fig, out / "02_tsne_layer_panels.png")


def plot_gender_separation_curve(hs: np.ndarray, meta: pd.DataFrame,
                                 model_key: str, out: Path) -> np.ndarray:
    """
    cosine distance between female/male story centroids
    at every single layer.  Rising curve = bias deepens with network depth.
    """
    n_layers = hs.shape[1]
    fm = (meta["protagonist_gender"] == "female").values
    mm = (meta["protagonist_gender"] == "male").values

    dists = np.array([
        _centroid_cos_dist(hs[:, l, :], fm, mm)
        for l in range(n_layers)
    ])

    peak = int(np.argmax(dists))
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(range(n_layers), dists, "o-", color="#C44E52", linewidth=2, markersize=5)
    ax.fill_between(range(n_layers), dists, alpha=0.12, color="#C44E52")
    ax.axvline(peak, color="#C44E52", linestyle="--", alpha=0.7,
               label=f"Peak  layer {peak}  (dist = {dists[peak]:.4f})")
    ax.set_xlabel("Transformer Layer  (0 = embedding)")
    ax.set_ylabel("Cosine Distance\n(female centroid  vs  male centroid)")
    ax.set_title(
        f"Gender Bias Signal Across Transformer Layers : {model_key}\n"
        "Higher = more gender-separated hidden space at that depth",
        fontweight="bold",
    )
    ax.legend(fontsize=9)
    ax.set_xticks(range(n_layers))
    ax.set_facecolor("#f8f8f8")
    plt.tight_layout()
    _save(fig, out / "03_gender_separation_curve.png")
    print(f"    Peak gender separation: layer {peak}  (dist={dists[peak]:.4f})")
    return dists


def plot_probe_accuracy_curve(hs: np.ndarray, meta: pd.DataFrame,
                              model_key: str, out: Path) -> np.ndarray:
    """
    Linear probe (logistic regression, 5-fold CV) at every layer.
    Answers: can we predict protagonist gender from the hidden state?
    Accuracy well above 50 % = gender is encoded at that depth.
    """
    n_layers = hs.shape[1]
    y = (meta["protagonist_gender"] == "female").values.astype(int)
    print(f"    Running linear probe on {n_layers} layers …")

    accs = np.array([_probe_acc(hs[:, l, :], y) for l in range(n_layers)])

    peak = int(np.argmax(accs))
    fig, ax = plt.subplots(figsize=(10, 5))
    colors = ["#C44E52" if i == peak else "#4C72B0" for i in range(n_layers)]
    ax.bar(range(n_layers), accs * 100, color=colors, alpha=0.85, edgecolor="white")
    ax.axhline(50, color="gray", linestyle="--", linewidth=1, label="Chance (50 %)")
    ax.axhline(accs.max() * 100, color="#C44E52", linestyle=":",
               label=f"Peak  {accs.max()*100:.1f} %  @  layer {peak}")
    ax.set_xlabel("Transformer Layer")
    ax.set_ylabel("Probe Accuracy (%)")
    ax.set_title(
        f"Gender Prediction from Hidden States : {model_key}\n"
        "Linear probe (logistic regression, 5-fold CV)",
        fontweight="bold",
    )
    ax.set_xticks(range(n_layers))
    ax.legend(fontsize=9)
    ax.set_ylim(40, min(100, accs.max() * 100 + 5))
    ax.set_facecolor("#f8f8f8")
    plt.tight_layout()
    _save(fig, out / "04_probe_accuracy_curve.png")
    print(f"    Peak probe accuracy:    layer {peak}  ({accs.max()*100:.1f} %)")
    return accs


def plot_region_separation_curve(hs: np.ndarray, meta: pd.DataFrame,
                                 model_key: str, out: Path) -> None:
    """
    Mean pairwise cosine distance between cultural region centroids per layer.
    Low = cultures are conflated; high = culturally distinct representations.
    """
    n_layers = hs.shape[1]
    regions  = [r for r in REG_COLORS if (meta["region"] == r).any()]
    if len(regions) < 2:
        print("    Too few regions --> skipping region separation curve.")
        return

    mean_dists = np.zeros(n_layers)
    for l in range(n_layers):
        centroids = np.array([
            hs[(meta["region"] == r).values, l, :].mean(0) for r in regions
        ])
        mean_dists[l] = pdist(centroids, metric="cosine").mean()

    peak = int(np.argmax(mean_dists))
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(range(n_layers), mean_dists, "s-", color="#55A868", linewidth=2, markersize=5)
    ax.fill_between(range(n_layers), mean_dists, alpha=0.12, color="#55A868")
    ax.axvline(peak, color="#55A868", linestyle="--", alpha=0.7,
               label=f"Peak  layer {peak}  (dist = {mean_dists[peak]:.4f})")
    ax.set_xlabel("Transformer Layer  (0 = embedding)")
    ax.set_ylabel("Mean Pairwise Cosine Distance\n(region centroids)")
    ax.set_title(
        f"Cultural Region Separation Across Transformer Layers : {model_key}\n"
        "Higher = more culturally distinct semantic space at that depth",
        fontweight="bold",
    )
    ax.legend(fontsize=9)
    ax.set_xticks(range(n_layers))
    ax.set_facecolor("#f8f8f8")
    plt.tight_layout()
    _save(fig, out / "05_region_separation_curve.png")
    print(f"    Peak region separation: layer {peak}  (dist={mean_dists[peak]:.4f})")


