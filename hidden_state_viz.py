def _save(fig: plt.Figure, path: Path) -> None:
    fig.savefig(path, dpi=FIG_DPI, bbox_inches="tight")
    plt.close(fig)
    print(f"    saved → {path.name}")


def _pca2(X: np.ndarray) -> np.ndarray:
    n_comp = min(2, X.shape[0] - 1, X.shape[1])
    return PCA(n_components=n_comp, random_state=RANDOM_STATE).fit_transform(X)


def _tsne2(X: np.ndarray) -> np.ndarray:
    pca50 = PCA(n_components=min(50, X.shape[1], X.shape[0] - 1),
                random_state=RANDOM_STATE).fit_transform(X)
    return TSNE(n_components=2, perplexity=min(40, len(X) // 4),
                max_iter=600, init="pca", learning_rate="auto",
                random_state=RANDOM_STATE).fit_transform(pca50)


def _centroid_cos_dist(vecs: np.ndarray, mask_a: np.ndarray,
                       mask_b: np.ndarray) -> float:
    ca, cb = vecs[mask_a].mean(0), vecs[mask_b].mean(0)
    return float(cosine(ca, cb))


def _probe_acc(X: np.ndarray, y: np.ndarray, cv: int = 5) -> float:
    Xs = StandardScaler().fit_transform(X)
    clf = LogisticRegression(max_iter=300, C=1.0, solver="lbfgs")
    scores = cross_val_score(
        clf, Xs, y,
        cv=StratifiedKFold(min(cv, int(y.sum()), int((~y.astype(bool)).sum())),
                           shuffle=True, random_state=RANDOM_STATE),
        scoring="accuracy",
    )
    return float(scores.mean())


def _panel_layer_indices(n_layers: int, requested: list[int] | None) -> list[int]:
    if requested:
        return [l for l in requested if l < n_layers]
    # default: embedding + 4 evenly spaced including final
    idxs = [0]
    for frac in [0.25, 0.50, 0.75, 1.0]:
        idx = round(frac * (n_layers - 1))
        if idx not in idxs:
            idxs.append(idx)
    return idxs


